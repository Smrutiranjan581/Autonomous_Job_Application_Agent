@app.route("/upload-resume", methods=["POST"])
def upload_resume():
    if "file" not in request.files:
        return jsonify({"error": "No file provided"}), 400
    file = request.files["file"]
    if not file.filename:
        return jsonify({"error": "Empty filename"}), 400
    os.makedirs("data", exist_ok=True)
    path = f"data/{file.filename}"
    file.save(path)

    # Auto-parse and store resume text in session context
    try:
        from src.resume_tools import parse_resume
        text = parse_resume.invoke(path)
        app.config["RESUME_TEXT"] = text
        app.config["RESUME_PATH"] = path
    except Exception as e:
        return jsonify({"error": f"File saved but parse failed: {e}"}), 500

    return jsonify({"message": f"Resume '{file.filename}' uploaded and parsed!", "path": path})


@app.route("/upload-job", methods=["POST"])
def upload_job():
    # Handle file upload
    if "file" in request.files:
        file = request.files["file"]
        if not file.filename:
            return jsonify({"error": "Empty filename"}), 400
        os.makedirs("data", exist_ok=True)
        path = f"data/{file.filename}"
        file.save(path)
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            text = f.read()
    # Handle plain text paste
    elif request.json and request.json.get("text"):
        text = request.json["text"]
        os.makedirs("data", exist_ok=True)
        path = "data/job_description.txt"
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        return jsonify({"error": "No file or text provided"}), 400

    app.config["JOB_TEXT"] = text
    app.config["JOB_PATH"] = path
    return jsonify({"message": "Job description uploaded successfully!", "path": path, "preview": text[:300]})


