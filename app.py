def _build_pdf(content, title="Document"):
    """Build a styled PDF and return its download URL."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.lib import colors
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
    from reportlab.lib.enums import TA_LEFT, TA_CENTER

    os.makedirs("outputs", exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename  = f"{title.replace(' ','_')}_{timestamp}.pdf"
    filepath  = f"outputs/{filename}"

    doc    = SimpleDocTemplate(filepath, pagesize=A4,
                               leftMargin=2.5*cm, rightMargin=2.5*cm,
                               topMargin=2.5*cm, bottomMargin=2.5*cm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("T", parent=styles["Normal"], fontSize=18,
                                 fontName="Helvetica-Bold",
                                 textColor=colors.HexColor("#2c2c6c"),
                                 spaceAfter=6, alignment=TA_CENTER)
    sub_style   = ParagraphStyle("S", parent=styles["Normal"], fontSize=10,
                                 textColor=colors.HexColor("#888888"),
                                 spaceAfter=4, alignment=TA_CENTER)
    body_style  = ParagraphStyle("B", parent=styles["Normal"], fontSize=11,
                                 leading=18, textColor=colors.HexColor("#222222"),
                                 spaceAfter=10, alignment=TA_LEFT)
    foot_style  = ParagraphStyle("F", parent=styles["Normal"], fontSize=8,
                                 textColor=colors.grey, alignment=TA_CENTER)

    story = [
        Paragraph(title.replace("_", " "), title_style),
        Paragraph(f"Generated on {datetime.now().strftime('%B %d, %Y')}", sub_style),
        Spacer(1, 0.3*cm),
        HRFlowable(width="100%", thickness=1.5,
                   color=colors.HexColor("#6c63ff"), spaceAfter=14),
    ]
    for line in content.split("\n"):
        line = line.strip()
        if not line:
            story.append(Spacer(1, 0.3*cm))
        else:
            safe = line.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;")
            story.append(Paragraph(safe, body_style))
    story += [
        Spacer(1, 0.5*cm),
        HRFlowable(width="100%", thickness=0.5,
                   color=colors.HexColor("#cccccc"), spaceAfter=8),
        Paragraph("Generated by Job Application AI Agent", foot_style)
    ]
    doc.build(story)
    return f"/download-pdf/{filename}"


@app.route("/chat", methods=["POST"])
def chat():
    data = request.json or {}
    user_message = data.get("message", "").strip()
    if not user_message:
        return jsonify({"error": "Empty message"}), 400

    api_key = os.getenv("OPENAI_API_KEY", "")
    if not api_key or api_key.startswith("<"):
        return jsonify({"error": "OPENAI_API_KEY not set. Add your key to the .env file."}), 500

    # Inject uploaded resume + job context automatically
    context_prefix = ""
    resume_text = app.config.get("RESUME_TEXT", "")
    job_text    = app.config.get("JOB_TEXT", "")
    if resume_text:
        context_prefix += f"[RESUME CONTENT]:\n{resume_text[:3000]}\n\n"
    if job_text:
        context_prefix += f"[JOB DESCRIPTION]:\n{job_text[:3000]}\n\n"
    full_message = context_prefix + user_message if context_prefix else user_message

    try:
        agent = get_agent()
        response = agent.invoke(
            {"input": full_message},
            config={"configurable": {"session_id": "ui-session"}}
        )
        output = response["output"]
        app.config["LAST_AGENT_OUTPUT"] = output

        # Auto-generate PDF if response looks like a cover letter
        pdf_url = None
        cover_keywords = ["dear hiring", "dear recruiter", "i am writing", "cover letter", "sincerely", "yours faithfully"]
        if any(kw in output.lower() for kw in cover_keywords):
            try:
                pdf_url = _build_pdf(output, "Cover_Letter")
            except Exception:
                pass

        return jsonify({"response": output, "pdf_url": pdf_url})
    except Exception as e:
        traceback.print_exc()
        err = str(e)
        if "401" in err or "invalid_api_key" in err or "Incorrect API key" in err:
            return jsonify({"error": "Invalid OpenAI API key. Get a new one at platform.openai.com/api-keys"}), 401
        if "insufficient_quota" in err:
            return jsonify({"error": "OpenAI quota exceeded. Check billing at platform.openai.com"}), 402
        return jsonify({"error": f"Agent error: {err}"}), 500


